export const translations: Record<AppLanguage, TranslationMap> = {
  en,
  fr,
  es,
  ar,
  zh,
  pt,
  de,
};

export function translate(
  language: AppLanguage,
  key: string,
  params?: Record<string, string | number>,
) {
  const localized = translations[language][key];
  const english = translations.en[key];
  const template = localized ?? english ?? key;

  if (!localized && typeof process !== 'undefined' && process.env.NODE_ENV !== 'production') {
    console.warn(`[i18n] Missing translation for "${key}" in "${language}".`);
  }

  if (!english && typeof process !== 'undefined' && process.env.NODE_ENV !== 'production') {
    console.warn(`[i18n] Missing English fallback for "${key}".`);
  }

  if (!params) {
    return template;
  }

  return Object.entries(params).reduce(
    (value, [paramKey, paramValue]) => value.replaceAll(`{${paramKey}}`, String(paramValue)),
    template,
  );
}
